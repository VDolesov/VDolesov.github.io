def text_page(path, title, meta, crumbs, eyebrow, h1, lead, body, active=""):
    main = f"""  <main id="main">
{page_hero(crumbs, eyebrow, h1, lead)}
    <section class="text-page">
      <div class="shell">
{body}
      </div>
    </section>
  </main>
"""
    write(path + "index.html",
          page(title, meta, "/" + path, main, SECTIONS, active or "/" + path))


def prose(*paragraphs):
    return "\n".join(f"        <p>{p}</p>" for p in paragraphs)


def facts(items):
    rows = "".join(f"<div><dt>{esc(k)}</dt><dd>{v}</dd></div>" for k, v in items)
    return f'        <dl class="fact-list">{rows}</dl>'


def steps(items):
    rows = "".join(
        f"<li><span>{i + 1:02d}</span><div><h3>{esc(t)}</h3><p>{d}</p></div></li>"
        for i, (t, d) in enumerate(items))
    return f'        <ol class="step-list">{rows}</ol>'


def empty_state(title, text, link_text="Перейти в каталог", link="/catalog/"):
    return f"""        <div class="empty-state">
          <span>—</span>
          <h2>{esc(title)}</h2>
          <p>{text}</p>
          <a class="button button--outline" href="{link}">{esc(link_text)}</a>
        </div>"""


